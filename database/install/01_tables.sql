-- -----------------------------------------------------------------------------
-- PRT : Printing - Job Order (Blueprint bagian 3)
-- -----------------------------------------------------------------------------
create table prt_job_order (
   job_id            number generated by default on null as identity
 , job_no            varchar2(30)
 , bu_id             number        not null
 , customer_id       number
 , job_type          varchar2(10)  default 'MTO' not null
 , product_desc      varchar2(500) not null
 , qty_order         number        not null
 , ups_per_sheet     number        default 1 not null
 , insheet_pct       number        default 5 not null
 , due_date          date
 , selling_price     number        default 0 not null
 -- Estimasi HPP per komponen (Blueprint 3.3)
 , est_paper         number        default 0 not null
 , est_ink           number        default 0 not null
 , est_plate         number        default 0 not null
 , est_machine       number        default 0 not null
 , est_finishing     number        default 0 not null
 , est_labor         number        default 0 not null
 , est_overhead      number        default 0 not null
 , est_hpp           number generated always as (est_paper + est_ink + est_plate + est_machine + est_finishing + est_labor + est_overhead) virtual
 -- Realisasi
 , qty_produced      number        default 0 not null
 , qty_reject        number        default 0 not null
 , qty_delivered     number        default 0 not null
 , act_other_cost    number        default 0 not null
 , status            varchar2(20)  default 'DRAFT' not null
 , notes             varchar2(1000)
 , created_by        varchar2(255)
 , created_on        date
 , updated_by        varchar2(255)
 , updated_on        date
 , constraint prt_job_order_pk primary key (job_id)
 , constraint prt_job_order_no_uk unique (job_no)
 , constraint prt_job_type_ck check (job_type in ('MTO','STOCK'))
 , constraint prt_job_status_ck check (status in ('DRAFT','SUBMITTED','APPROVED','REJECTED','IN_PROGRESS','COMPLETED','CLOSED','CANCELLED'))
 , constraint prt_job_mto_cust_ck check (job_type = 'STOCK' or customer_id is not null)
 , constraint prt_job_bu_fk foreign key (bu_id) references mdm_business_unit (bu_id)
 , constraint prt_job_cust_fk foreign key (customer_id) references mdm_customer (customer_id)
);

