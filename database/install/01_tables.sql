-- -----------------------------------------------------------------------------
-- SYS : security, penomoran dokumen, approval engine
-- -----------------------------------------------------------------------------
create table sys_role (
   role_code      varchar2(30)  not null
 , role_name      varchar2(100) not null
 , description    varchar2(400)
 , constraint sys_role_pk primary key (role_code)
);

create table sys_user_role (
   user_role_id   number generated by default on null as identity
 , username       varchar2(255) not null
 , role_code      varchar2(30)  not null
 , created_by     varchar2(255)
 , created_on     date
 , updated_by     varchar2(255)
 , updated_on     date
 , constraint sys_user_role_pk primary key (user_role_id)
 , constraint sys_user_role_uk unique (username, role_code)
 , constraint sys_user_role_role_fk foreign key (role_code) references sys_role (role_code)
);

-- Jenis dokumen: prefix nomor + aturan approval (Blueprint 6.1, D-11 configurable)
create table sys_doc_type (
   doc_type        varchar2(10)  not null
 , doc_name        varchar2(100) not null
 , prefix          varchar2(10)  not null
 , approver1_role  varchar2(30)
 , approver2_role  varchar2(30)
 , level2_limit    number        default 0 not null
 , constraint sys_doc_type_pk primary key (doc_type)
 , constraint sys_doc_type_r1_fk foreign key (approver1_role) references sys_role (role_code)
 , constraint sys_doc_type_r2_fk foreign key (approver2_role) references sys_role (role_code)
);

create table sys_doc_seq (
   doc_type   varchar2(10) not null
 , bu_code    varchar2(10) not null
 , period     varchar2(4)  not null
 , last_no    number       default 0 not null
 , constraint sys_doc_seq_pk primary key (doc_type, bu_code, period)
);

create table sys_approval (
   approval_id     number generated by default on null as identity
 , doc_type        varchar2(10)  not null
 , doc_id          number        not null
 , doc_no          varchar2(30)
 , bu_id           number
 , approval_level  number        default 1 not null
 , approver_role   varchar2(30)  not null
 , amount          number
 , requested_by    varchar2(255) not null
 , requested_on    date          default sysdate not null
 , status          varchar2(20)  default 'PENDING' not null
 , acted_by        varchar2(255)
 , acted_on        date
 , note            varchar2(1000)
 , constraint sys_approval_pk primary key (approval_id)
 , constraint sys_approval_status_ck check (status in ('PENDING','APPROVED','REJECTED','CANCELLED'))
 , constraint sys_approval_dt_fk foreign key (doc_type) references sys_doc_type (doc_type)
);
create index sys_approval_doc_i on sys_approval (doc_type, doc_id);

