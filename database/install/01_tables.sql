);

-- -----------------------------------------------------------------------------
-- PUR : Purchase Requisition (Blueprint 5.2)
-- -----------------------------------------------------------------------------
create table pur_requisition (
   pr_id          number generated by default on null as identity
 , pr_no          varchar2(30)
 , bu_id          number        not null
 , pr_date        date          default trunc(sysdate) not null
 , purpose        varchar2(10)  default 'STOCK' not null
 , job_id         number
 , project_id     number
 , wbs_id         number
 , requested_by   varchar2(255)
 , need_date      date
 , description    varchar2(1000)
 , status         varchar2(20)  default 'DRAFT' not null
 , created_by     varchar2(255)
 , created_on     date
 , updated_by     varchar2(255)
 , updated_on     date
 , constraint pur_requisition_pk primary key (pr_id)
 , constraint pur_requisition_no_uk unique (pr_no)
 , constraint pur_req_purpose_ck check (purpose in ('STOCK','JOB','PROJECT'))
 , constraint pur_req_status_ck check (status in ('DRAFT','SUBMITTED','APPROVED','REJECTED','CANCELLED','CLOSED'))
 , constraint pur_req_ref_ck check (
        (purpose = 'STOCK')
     or (purpose = 'JOB' and job_id is not null)
     or (purpose = 'PROJECT' and project_id is not null))
 , constraint pur_req_bu_fk foreign key (bu_id) references mdm_business_unit (bu_id)
 , constraint pur_req_job_fk foreign key (job_id) references prt_job_order (job_id)
 , constraint pur_req_project_fk foreign key (project_id) references prj_project (project_id)
 , constraint pur_req_wbs_fk foreign key (wbs_id) references prj_wbs (wbs_id)
);

create table pur_requisition_line (
   line_id     number generated by default on null as identity
 , pr_id       number        not null
 , line_no     number
 , item_id     number        not null
 , qty         number        not null
 , unit_price  number        default 0 not null
 , line_amount number generated always as (qty * unit_price) virtual
 , notes       varchar2(500)
 , created_by  varchar2(255)
 , created_on  date
 , updated_by  varchar2(255)
 , updated_on  date
 , constraint pur_req_line_pk primary key (line_id)
 , constraint pur_req_line_qty_ck check (qty > 0)
 , constraint pur_req_line_pr_fk foreign key (pr_id) references pur_requisition (pr_id) on delete cascade
 , constraint pur_req_line_item_fk foreign key (item_id) references mdm_item (item_id)
);
create index pur_req_line_pr_i on pur_requisition_line (pr_id);

-- -----------------------------------------------------------------------------
-- INV : Stock ledger (Blueprint 5.3; BR-07 stok hanya dari transaksi tercatat)
-- Transaksi tidak dihapus/diubah; koreksi lewat transaksi baru (reversal).
-- -----------------------------------------------------------------------------
create table inv_stock_txn (
   txn_id        number generated by default on null as identity
 , txn_no        varchar2(30)
 , txn_date      date          default trunc(sysdate) not null
 , txn_type      varchar2(10)  not null
 , bu_id         number
 , warehouse_id  number        not null
 , item_id       number        not null
 , qty           number        not null
 , qty_signed    number
 , unit_cost     number
 , total_cost    number generated always as (qty * nvl(unit_cost,0)) virtual
 , job_id        number
 , project_id    number
 , wbs_id        number
 , reference     varchar2(100)
 , notes         varchar2(500)
 , created_by    varchar2(255)
 , created_on    date
 , updated_by    varchar2(255)
 , updated_on    date
 , constraint inv_stock_txn_pk primary key (txn_id)
 , constraint inv_stock_txn_no_uk unique (txn_no)
 , constraint inv_txn_type_ck check (txn_type in ('RECEIPT','ISSUE','RETURN','ADJ_IN','ADJ_OUT'))
 , constraint inv_txn_qty_ck check (qty > 0)
 , constraint inv_txn_issue_ref_ck check (txn_type not in ('ISSUE','RETURN') or job_id is not null or project_id is not null)
 , constraint inv_txn_bu_fk foreign key (bu_id) references mdm_business_unit (bu_id)
 , constraint inv_txn_wh_fk foreign key (warehouse_id) references mdm_warehouse (warehouse_id)
 , constraint inv_txn_item_fk foreign key (item_id) references mdm_item (item_id)
 , constraint inv_txn_job_fk foreign key (job_id) references prt_job_order (job_id)
 , constraint inv_txn_project_fk foreign key (project_id) references prj_project (project_id)
 , constraint inv_txn_wbs_fk foreign key (wbs_id) references prj_wbs (wbs_id)
);
create index inv_txn_item_wh_i on inv_stock_txn (item_id, warehouse_id);
create index inv_txn_job_i on inv_stock_txn (job_id);
create index inv_txn_project_i on inv_stock_txn (project_id, wbs_id);
